'use strict';

const agg = require('./aggregate');
const fmt = require('./format');

// Tree nodes are plain objects so the whole tree can be built and tested without VS Code:
// { id, label, collapsible: 'none'|'collapsed'|'expanded', description?, icon?, tooltip? (plain), markdown?, children?() }

function leaf(id, label, options = {}) {
  return { ...options, id, label, collapsible: 'none' };
}

function branch(id, label, children, options = {}) {
  const { expanded, ...rest } = options;
  return { ...rest, id, label, collapsible: expanded ? 'expanded' : 'collapsed', children };
}

function folderName(cwd) {
  const parts = String(cwd).split(/[\\/]/).filter(Boolean);
  return parts.length ? parts[parts.length - 1] : String(cwd);
}

function sessionTitle(sessionId, meta) {
  const summary = meta && meta.summary ? fmt.oneLine(meta.summary, 60) : '';
  if (summary) {
    return summary;
  }
  if (meta && meta.cwd) {
    return `${folderName(meta.cwd)} · ${sessionId.slice(0, 8)}`;
  }
  return `Session ${sessionId.slice(0, 8)}`;
}

function modelList(rows) {
  return agg.modelBreakdown(rows).map((m) => m.model).join(', ');
}

function sessionDetails(session, meta) {
  return [
    meta && meta.cwd ? `Folder: ${meta.cwd}` : null,
    meta && (meta.repository || meta.branch) ? `Repository: ${[meta.repository, meta.branch].filter(Boolean).join(' @ ')}` : null,
    `Started: ${fmt.dateTime((meta && meta.createdAt) || session.totals.firstTs)}`,
    `Last call: ${fmt.dateTime(session.totals.lastTs)}`,
    `Models: ${modelList(session.rows)}`,
    `Session id: ${session.sessionId}`,
  ];
}

function callsDescription(totals) {
  return totals.calls ? `${fmt.full(totals.calls)} · avg ${fmt.duration(totals.durationMs / totals.calls)}` : '0';
}

function metricNodes(prefix, totals) {
  const avgTtft = totals.ttftCalls ? fmt.duration(totals.ttftMs / totals.ttftCalls) : '–';
  return [
    branch(`${prefix}/input`, 'Input', () => [
      leaf(`${prefix}/input/fresh`, 'Fresh (uncached)', {
        description: fmt.full(totals.fresh),
        icon: 'circle-outline',
        tooltip: 'Prompt tokens processed without a cache hit.',
      }),
      leaf(`${prefix}/input/cache-read`, 'Cache read', {
        description: `${fmt.full(totals.cacheRead)} · ${fmt.percent(totals.cacheRead, totals.input)}`,
        icon: 'database',
        tooltip: 'Prompt tokens served from the prompt cache (billed at a lower rate).',
      }),
      leaf(`${prefix}/input/cache-write`, 'Cache write', {
        description: fmt.full(totals.cacheWrite),
        icon: 'save',
        tooltip: 'Prompt tokens written to the prompt cache.',
      }),
    ], {
      description: fmt.full(totals.input),
      icon: 'sign-in',
      tooltip: 'Prompt tokens sent to the model: fresh + cache read + cache write.',
    }),
    leaf(`${prefix}/output`, 'Output', {
      description: fmt.full(totals.output),
      icon: 'sign-out',
      tooltip: 'Tokens generated by the model.',
    }),
    leaf(`${prefix}/reasoning`, 'Reasoning', {
      description: fmt.full(totals.reasoning),
      icon: 'lightbulb',
      tooltip: fmt.REASONING_NOTE,
    }),
    leaf(`${prefix}/credits`, 'AI credits', {
      description: fmt.credits(totals.nanoAiu),
      icon: 'credit-card',
      tooltip: 'AI credits billed by Copilot for these calls.',
    }),
    leaf(`${prefix}/calls`, 'Model calls', {
      description: callsDescription(totals),
      icon: 'pulse',
      tooltip: `Average call duration ${fmt.duration(totals.calls ? totals.durationMs / totals.calls : 0)}, average time to first token ${avgTtft}.`,
    }),
  ];
}

function modelNodes(prefix, models) {
  return models.map(({ model, totals }) => leaf(`${prefix}/${model}`, model, {
    description: fmt.summaryLine(totals),
    icon: 'circuit-board',
    markdown: fmt.totalsTooltip(model, [], totals),
  }));
}

function bucketChildren(prefix, rows) {
  const nodes = metricNodes(prefix, agg.summarise(rows));
  const models = agg.modelBreakdown(rows);
  if (models.length > 0) {
    nodes.push(branch(`${prefix}/models`, 'By model', () => modelNodes(`${prefix}/models`, models), {
      icon: 'layers',
      description: String(models.length),
    }));
  }
  return nodes;
}

function callIcon(row) {
  if (row.initiator === 'user') {
    return 'person';
  }
  if (row.initiator === 'compaction') {
    return 'fold';
  }
  return row.agentId ? 'hubot' : 'circle-small';
}

function callNode(prefix, row) {
  const lines = [
    row.initiator ? `Initiator: ${row.initiator}` : null,
    row.reasoningEffort ? `Reasoning effort: ${row.reasoningEffort}` : null,
    row.finishReason ? `Finish reason: ${row.finishReason}` : null,
    `Duration: ${fmt.duration(row.durationMs)} · first token after ${fmt.duration(row.ttftMs)}`,
  ];
  return leaf(`${prefix}/call:${row.id}`, `${fmt.timeWithSeconds(row.ts)} ${row.model}`, {
    description: fmt.summaryLine(row),
    icon: callIcon(row),
    markdown: fmt.totalsTooltip(`${row.model} · ${fmt.dateTime(row.ts)}`, lines, { ...row, calls: 1 }, { showCalls: false }),
  });
}

function subAgentNode(prefix, agent, index) {
  const id = `${prefix}/agent:${agent.agentId}`;
  const label = `Sub-agent ${index + 1}`;
  return branch(id, label, () => agent.rows.map((row) => callNode(id, row)), {
    description: fmt.summaryLine(agent.totals),
    icon: 'hubot',
    markdown: fmt.totalsTooltip(label, [`Agent id: ${agent.agentId}`, `Models: ${modelList(agent.rows)}`], agent.totals),
  });
}

function turnNodes(prefix, turns, now) {
  return turns.map((turn) => {
    const id = `${prefix}/${turn.key}`;
    const label = turn.turnIndex === null ? 'Turn ?' : `Turn ${turn.turnIndex}`;
    const subAgentCalls = turn.rows.length - turn.mainRows.length;
    const lines = [
      `Started: ${fmt.dateTime(turn.totals.firstTs)}`,
      `Main agent: ${turn.mainRows.length} calls`,
      turn.subAgents.length ? `Sub-agents: ${turn.subAgents.length} (${subAgentCalls} calls)` : null,
      `Models: ${modelList(turn.rows)}`,
    ];
    return branch(id, label, () => [
      ...turn.mainRows.map((row) => callNode(id, row)),
      ...turn.subAgents.map((agent, index) => subAgentNode(id, agent, index)),
    ], {
      description: `${fmt.when(turn.totals.firstTs, now)} · ${fmt.summaryLine(turn.totals)}`,
      icon: 'comment',
      markdown: fmt.totalsTooltip(label, lines, turn.totals),
    });
  });
}

function sessionChildren(prefix, rows, now) {
  const nodes = bucketChildren(prefix, rows);
  const turns = agg.turnBreakdown(rows);
  nodes.push(branch(`${prefix}/turns`, 'Turns', () => turnNodes(`${prefix}/turns`, turns, now), {
    icon: 'list-ordered',
    description: String(turns.length),
  }));
  return nodes;
}

function sessionNode(id, label, session, sessionMeta, now, options = {}) {
  const meta = sessionMeta.get(session.sessionId) || null;
  const title = sessionTitle(session.sessionId, meta);
  const heading = meta && meta.summary ? fmt.oneLine(meta.summary, 200) : title;
  return branch(id, label || title, () => sessionChildren(id, session.rows, now), {
    expanded: options.expanded,
    icon: options.icon || 'comment-discussion',
    description: label
      ? `${title} · ${fmt.summaryLine(session.totals)}`
      : `${fmt.when(session.totals.lastTs, now)} · ${fmt.summaryLine(session.totals)}`,
    markdown: fmt.totalsTooltip(heading, sessionDetails(session, meta), session.totals),
  });
}

function countSessions(rows) {
  return new Set(rows.map((row) => row.sessionId)).size;
}

function periodNode(period, rows, now) {
  const since = agg.periodStart(period.days, now);
  const periodRows = agg.rowsSince(rows, since);
  const totals = agg.summarise(periodRows);
  const id = `period:${period.key}`;
  return branch(id, period.label, () => bucketChildren(id, periodRows), {
    icon: 'calendar',
    description: periodRows.length ? fmt.summaryLine(totals) : 'no calls',
    markdown: fmt.totalsTooltip(period.label, [
      `Since: ${fmt.dateTime(since || totals.firstTs)}`,
      `Sessions: ${countSessions(periodRows)}`,
    ], totals),
  });
}

function dailyNodes(rows, now, days) {
  return agg.dayBreakdown(agg.rowsSince(rows, agg.periodStart(days, now))).map((day) => {
    const id = `daily/${day.day}`;
    const label = fmt.dayLabel(day.totals.firstTs);
    return branch(id, label, () => bucketChildren(id, day.rows), {
      icon: 'calendar',
      description: fmt.summaryLine(day.totals),
      markdown: fmt.totalsTooltip(label, [`Sessions: ${countSessions(day.rows)}`], day.totals),
    });
  });
}

/** Builds the root nodes from a UsageStore-like object: { rows, sessions, error, dbPath }. */
function buildRoots(store, options = {}) {
  const now = options.now || Date.now();
  const recentSessionCount = options.recentSessionCount || 20;
  const dailyHistoryDays = options.dailyHistoryDays || 14;

  if (store.error) {
    return [leaf('error', store.error.message, {
      icon: 'warning',
      tooltip: `${store.error.message}\nDatabase: ${store.dbPath}`,
    })];
  }
  const rows = store.rows;
  if (rows.length === 0) {
    return [leaf('empty', 'No Copilot model calls recorded yet', {
      icon: 'info',
      tooltip: `Watching ${store.dbPath}`,
    })];
  }

  const sessions = agg.sessionBreakdown(rows);
  const currentId = agg.latestSessionId(rows);
  const current = sessions.find((s) => s.sessionId === currentId) || sessions[0];
  const recent = sessions.slice(0, recentSessionCount);

  return [
    sessionNode('current', 'Current session', current, store.sessions, now, { expanded: true, icon: 'pulse' }),
    ...agg.PERIODS.map((period) => periodNode(period, rows, now)),
    branch('sessions', 'Recent sessions', () => recent.map((s) => sessionNode(`sessions/${s.sessionId}`, null, s, store.sessions, now)), {
      icon: 'history',
      description: `${recent.length} of ${sessions.length}`,
    }),
    branch('daily', 'Daily', () => dailyNodes(rows, now, dailyHistoryDays), {
      icon: 'graph',
      description: `last ${dailyHistoryDays} days`,
    }),
  ];
}

module.exports = {
  buildRoots,
  sessionTitle,
};
